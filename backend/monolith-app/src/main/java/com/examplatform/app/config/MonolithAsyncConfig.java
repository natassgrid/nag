package com.examplatform.app.config;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.scheduling.concurrent.ThreadPoolTaskExecutor;

import java.util.concurrent.Executor;

/**
 * Thread pool configuration for asynchronous in-memory event dispatching in monolith mode.
 */
@Configuration
public class MonolithAsyncConfig {

    @Bean(name = "inMemoryEventExecutor")
    public Executor inMemoryEventExecutor() {
        ThreadPoolTaskExecutor executor = new ThreadPoolTaskExecutor();
        executor.setCorePoolSize(4);
        executor.setMaxPoolSize(16);
        executor.setQueueCapacity(500);
        executor.setThreadNamePrefix("MonolithEvent-");
        executor.initialize();
        return executor;
    }
}
