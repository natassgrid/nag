package com.examplatform.questionbank.extraction.dto;

import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.List;
import java.util.UUID;

/**
 * Request payload for resequencing / reordering extracted staging questions.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ResequenceQuestionsRequest {

    @NotNull(message = "orderedQuestionIds is required")
    @NotEmpty(message = "orderedQuestionIds must not be empty")
    private List<UUID> orderedQuestionIds;

    @Builder.Default
    private int startNumber = 1;
}
